"""Per-sample comparison of experiments against a reference one: paired differences, not just means.

With 24 samples the std over repeats (~3 EMD) mixes split noise with sample difficulty; comparing the
same samples under two settings (Wilcoxon signed-rank test) is the sharper test.
"""

import argparse

import numpy as np
import pandas as pd
from scipy.stats import spearmanr, wilcoxon

from soilgsd.config import load_config, resolve
from soilgsd.data import TARGET_COLS, load_labels
from soilgsd.metric import d_value, emd_parts


def per_sample(name: str, labels: pd.DataFrame) -> pd.DataFrame:
    """Mean over repeats of each sample's out-of-fold EMD (total, fine part, coarse part) and D50."""
    oof = pd.read_csv(resolve(f"outputs/{name}/oof.csv"))
    yt, yp = labels.loc[oof["sample_id"]].to_numpy(), oof[TARGET_COLS].to_numpy()
    fine, coarse = emd_parts(yt, yp)
    df = pd.DataFrame({"sample_id": oof["sample_id"], "emd": fine + coarse, "fine_part": fine,
                       "coarse_part": coarse, "pred_D50": d_value(yp, 50)})
    return df.groupby("sample_id").mean()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("reference")
    ap.add_argument("others", nargs="+")
    ap.add_argument("--out", default="reports/compare.md")
    args = ap.parse_args()
    cfg = load_config()
    labels = load_labels(cfg).set_index("sample_id")[TARGET_COLS].astype(float)
    folds = pd.read_csv(resolve(cfg["cv"]["folds_file"]))
    cls = folds.drop_duplicates("sample_id").set_index("sample_id")["d50_class"]

    ref = per_sample(args.reference, labels)
    table = pd.DataFrame({"class": cls.loc[ref.index], "true_D50": d_value(labels.loc[ref.index].to_numpy(), 50)},
                         index=ref.index)
    table[f"{args.reference} pred_D50"] = ref["pred_D50"]
    table[f"{args.reference} emd"] = ref["emd"]
    rows = []
    for name in args.others:
        other = per_sample(name, labels)
        table[f"{name} emd"] = other.loc[ref.index, "emd"]
        for col in ["emd", "fine_part", "coarse_part"]:
            for subset in ["all", "fine", "sand", "gravel"]:
                ids = ref.index if subset == "all" else cls[cls == subset].index.intersection(ref.index)
                d = other.loc[ids, col] - ref.loc[ids, col]
                rows.append({"experiment": name, "metric": col, "samples": subset, "n": len(d),
                             "mean diff (other - ref)": round(d.mean(), 2), "worse on": int((d > 0).sum()),
                             "wilcoxon p": round(wilcoxon(d).pvalue, 3)})
    rho = spearmanr(table["true_D50"], table[f"{args.reference} pred_D50"]).statistic
    lines = [
        f"# {', '.join(args.others)} vs {args.reference} (generated by scripts/compare_exps.py)",
        "",
        f"Spearman rank correlation of true and predicted D50 ({args.reference}): {rho:.2f}",
        "",
        "## Paired differences per sample (EMD averaged over the 3 repeats first)",
        pd.DataFrame(rows).to_markdown(index=False),
        "",
        "## Per sample, sorted by true D50",
        table.sort_values("true_D50").round(3).to_markdown(),
    ]
    resolve(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:6]))
    print(np.round(table.sort_values("true_D50"), 2).to_string())


if __name__ == "__main__":
    main()
