"""Ensemble of finished experiments: a weighted average of their curves with weights on the simplex.

Every member needs outputs/<name>/oof.csv (repeat 0 of data/folds.csv) and test curves (outputs/<name>/test_preds.csv
or submissions/<name>.csv); a model without test predictions cannot be in the ensemble.
- CV of the ensemble (honest): the weights for each fold are fitted on the other 5 folds and scored on it.
- Test: the final weights are fitted on all 24 OOF curves and applied to the members' test curves.
Writes outputs/<name>/{oof.csv, test_preds.csv}, submissions/<name>.csv, reports/ensemble/<name>.md and a row of
reports/results.csv.
"""

import argparse

import numpy as np
import pandas as pd

from soilgsd.config import load_config, resolve
from soilgsd.data import TARGET_COLS, load_labels
from soilgsd.ensemble import blend, error_correlation, fit_weights, load_member, nested_cv
from soilgsd.metric import emd_per_sample, is_valid_curve
from soilgsd.results import save_result, summarise


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("members", nargs="+", help="experiment names (outputs/<name>/)")
    ap.add_argument("--name", default="E1_ensemble")
    ap.add_argument("--config", default="configs/base.yaml")
    args = ap.parse_args()
    cfg = load_config(args.config)
    labels = load_labels(cfg).set_index("sample_id")[TARGET_COLS].astype(float)
    folds = pd.read_csv(resolve(cfg["cv"]["folds_file"]))
    f0 = folds[folds["repeat"] == 0].set_index("sample_id").loc[labels.index]
    cls = f0["d50_class"]
    test_ids = pd.Index(pd.read_csv(resolve(cfg["data"]["sample_submission"]))["sample_id"])

    loaded = [load_member(m, resolve("outputs"), resolve("submissions"), labels.index, test_ids) for m in args.members]
    oof = np.stack([o for o, _ in loaded])
    test = np.stack([t for _, t in loaded])
    y = labels.to_numpy()
    assert is_valid_curve(test.reshape(-1, 11), atol=1e-3).all(), "a member's test curve is not valid"

    def scores(p: np.ndarray) -> dict:
        e = pd.Series(emd_per_sample(y, p), index=labels.index)
        return {"EMD": e.mean(), **{c: e[cls == c].mean() for c in ["fine", "sand", "gravel"]}}

    ens_oof, fold_w = nested_cv(oof, y, f0["fold"].to_numpy())
    w_final = fit_weights(oof, y)
    rows = {m: scores(p) for m, p in zip(args.members, oof, strict=True)}
    rows["equal weights (nothing fitted)"] = scores(oof.mean(0))
    rows["fitted weights, nested CV (honest)"] = scores(ens_oof)
    rows["fitted weights, in-sample (optimistic)"] = scores(blend(oof, w_final))
    table = pd.DataFrame(rows).T.round(2)
    fold_w.columns = args.members
    weights = pd.DataFrame({"final weight": w_final}, index=args.members).round(3)

    test_curves = pd.DataFrame(blend(test, w_final), index=test_ids, columns=TARGET_COLS)
    assert is_valid_curve(test_curves.to_numpy(), atol=1e-6).all()
    out_dir = resolve(f"outputs/{args.name}")
    out_dir.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(ens_oof, index=labels.index, columns=TARGET_COLS).assign(repeat=0, fold=f0["fold"]).reset_index()[
        ["sample_id", "repeat", "fold", *TARGET_COLS]].to_csv(out_dir / "oof.csv", index=False)
    test_curves.reset_index().to_csv(out_dir / "test_preds.csv", index=False)
    test_curves.reset_index().to_csv(resolve(f"submissions/{args.name}.csv"), index=False)

    res = {"name": args.name, "approach": "ensemble", "backbone": " + ".join(args.members)}
    res.update(summarise(pd.read_csv(out_dir / "oof.csv"), load_labels(cfg), folds))
    res["compute"] = "cpu, seconds (linear programme on OOF curves)"
    save_result(res)

    report = resolve(f"reports/ensemble/{args.name}.md")
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join([
        f"# {args.name} (generated by scripts/ensemble.py)", "",
        "Weighted average of the members' curves, weights >= 0 summing to 1, fitted to minimise EMD on the OOF curves of",
        "repeat 0 (an exact linear programme). The honest CV fits the weights of each fold on the other 5 folds.", "",
        "## EMD on the 24 training samples (repeat 0)", table.to_markdown(), "",
        "## Final weights (fitted on all 24 OOF curves, used for the test submission)", weights.to_markdown(), "",
        "## Weights fitted inside the nested CV (one row per held-out fold)", fold_w.round(3).to_markdown(), "",
        "## Correlation of the members' per-sample EMD", error_correlation(oof, y, args.members).round(2).to_markdown(), "",
    ]) + "\n")
    print(table.to_string(), "\n")
    print(weights.to_string(), "\n")
    print(f"{report}\nsubmissions/{args.name}.csv")


if __name__ == "__main__":
    main()
